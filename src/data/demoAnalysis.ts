export function createDemoAnalysis(
  username?: string,
  goal: RecruiterGoal = 'alternance-frontend',
): PortfolioAnalysis {
  const normalizedUsername = username?.trim() || baseDemoAnalysis.user.login
  const user = {
    ...baseDemoAnalysis.user,
    login: normalizedUsername,
    name: normalizedUsername === baseDemoAnalysis.user.login ? baseDemoAnalysis.user.name : null,
    html_url: `https://github.com/${normalizedUsername}`,
  }
  const score = calculateScore(user, baseDemoAnalysis.repoSummary, goal)
  const recommendations = generateRecommendations(user, baseDemoAnalysis.repoSummary, score, goal)

  return {
    ...baseDemoAnalysis,
    user,
    score,
    recommendations,
  }
}
